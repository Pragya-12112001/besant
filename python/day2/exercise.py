# list
student_marks = [78, 85, 92]
print('marks: ', student_marks)
print('first mark: ', student_marks[0])
print('number of marks: ', len(student_marks))
print('data type: ', type(student_marks))

# tuples
stu_details = ('riya', 14, 78)
print('details: ', stu_details)
print('name: ', stu_details[0])
print('age: ', stu_details[1])
print('percentage: ', stu_details[2])
print('data type: ', type(stu_details))

# dict
stu_info = {
  "name": 'riya',
  "age": 14,
  "percentage": 78
}
print('details: ', stu_info)
print('name: ', stu_info['name'])
print('age: ', stu_info['age'])
print('percentage: ', stu_info['percentage'])
print('data type: ', type(stu_info))
